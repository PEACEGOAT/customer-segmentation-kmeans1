from sklearn.cluster import KMeans

# Memilih fitur yang akan dianalisis
# Kita fokus pada perilaku belanja: purchase_frequency dan total_revenue
features = ['purchase_frequency', 'total_revenue']
X = df_clean[features]

# Standarisasi Data
# Karena rentang frekuensi (1-20) dan revenue (100-10000) sangat jauh berbeda,
# kita harus menyamakan skalanya agar model tidak bias.
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# 3. Membuat Model K-Means Clustering
# Kita asumsikan kita ingin membagi pelanggan menjadi 3 segmen/kelompok
kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
df_clean['Cluster'] = kmeans.fit_predict(X_scaled) # Memasukkan label cluster ke DataFrame

# 4. Memvisualisasikan Hasil Clustering
plt.figure(figsize=(10, 6))
sns.scatterplot(
    x=df_clean['purchase_frequency'],
    y=df_clean['total_revenue'],
    hue=df_clean['Cluster'],
    palette=['#e74c3c', '#2ecc71', '#3498db'], # Warna merah, hijau, biru
    s=100, # Ukuran titik
    alpha=0.7
)
plt.title('Segmentasi Pelanggan Ritel (K-Means)', fontsize=16)
plt.xlabel('Frekuensi Pembelian')
plt.ylabel('Total Pendapatan')
plt.legend(title='Segmen Pelanggan')
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

# 5. Menampilkan Karakteristik tiap Segmen
print("Rata-Rata Perilaku Belanja per Segmen")
display(df_clean.groupby('Cluster')[features].mean().round(2))

"""Algoritma K-Means mengelompokkan data berdasarkan perhitungan jarak (Euclidean Distance). Pada data kita, fitur purchase_frequency memiliki rentang puluhan (1-20), sedangkan total_revenue memiliki rentang ribuan (100 - 10.000). Jika tidak distandarisasi, fitur total_revenue akan mendominasi perhitungan jarak murni karena angkanya lebih besar. StandardScaler menyamakan skala kedua fitur tersebut sehingga model K-Means tidak bias dan memperlakukan kedua fitur dengan bobot yang sama.

# **Interpretasi Bisnis dan Penamaan Segmen**
"""

# Menghitung rata-rata tiap cluster untuk dianalisis
cluster_summary = df_clean.groupby('Cluster')[['purchase_frequency', 'total_revenue']].mean().reset_index()

# Mengurutkan kelompok dari pendapatan (revenue) terendah ke tertinggi
cluster_summary = cluster_summary.sort_values(by='total_revenue').reset_index(drop=True)

# Membuat pemetaan nama segmen berdasarkan urutan pendapatan
# Karena kita membaginya menjadi 3 kelompok, secara logis urutannya adalah: Bawah, Tengah, Atas
segment_mapping = {
    cluster_summary.loc[0, 'Cluster']: '1. Pelanggan Biasa (Low Value)',
    cluster_summary.loc[1, 'Cluster']: '2. Pelanggan Reguler (Mid Value)',
    cluster_summary.loc[2, 'Cluster']: '3. Pelanggan VIP (High Value)'
}

# 4. Memasukkan nama segmen yang baru ke dalam data kita
df_clean['Customer_Segment'] = df_clean['Cluster'].map(segment_mapping)

# 5. Menampilkan hasil akhir yang siap dipresentasikan ke tim Marketing
print("PROFIL SEGMEN PELANGGAN")
final_report = df_clean.groupby('Customer_Segment').agg(
    Jumlah_Pelanggan=('age', 'count'),
    Rata_Rata_Frekuensi_Beli=('purchase_frequency', 'mean'),
    Rata_Rata_Total_Belanja=('total_revenue', 'mean')
).round(2)

display(final_report)

